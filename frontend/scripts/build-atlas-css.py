"""Generate src/v2/styles/atlas.css from docs/design-atlas/naff.css.

Every selector is scoped under :where(html[data-design="v2"]) so the new
design never leaks into the old one, and specificity stays exactly as in
the mockups (:where adds 0). Tokens live on `.nf` (body gets class="nf"
while design v2 is active); dark tokens follow the app theme
(html[data-nf="dark"]) as well as an explicit data-theme="dark".
Run: python3 frontend/scripts/build-atlas-css.py
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "docs/design-atlas/naff.css"
OUT = ROOT / "frontend/src/v2/styles/atlas.css"
P = ':where(html[data-design="v2"])'
PD = ':where(html[data-design="v2"][data-nf="dark"])'

css = SRC.read_text(encoding="utf-8")
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
out = []
for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
    sels, body = m.group(1).strip(), m.group(2).strip()
    new = []
    for s in [x.strip() for x in sels.split(",") if x.strip()]:
        if s == ":root":
            continue
        if s == '.nf[data-theme="dark"]':
            new += [f"{PD} .nf", f'{P} .nf[data-theme="dark"]']
            continue
        new.append(f"{P} {s}")
    if new:
        out.append(",".join(new) + "{" + body + "}")
header = (
    "/* GENERATED by frontend/scripts/build-atlas-css.py from docs/design-atlas/naff.css — do not edit by hand. */\n"
    "@import url('https://fonts.googleapis.com/css2?family=Onest:wght@400;500;600;700&family=JetBrains+Mono:wght@500;600&family=Unbounded:wght@500;600&display=swap');\n"
)
OUT.write_text(header + "\n".join(out) + "\n", encoding="utf-8")
print("rules:", len(out), "->", OUT)
